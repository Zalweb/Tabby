'use strict';
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
module.exports=async function testMethodLifecycle(db,{actor}) {
  const owner=randomUUID(),stranger=randomUUID();
  await db.exec('RESET ROLE');
  for(const id of [owner,stranger])await db.query("INSERT INTO public.users(id,display_name) VALUES ($1,'Synthetic method owner')",[id]);
  const change=async(kind,command,operation=randomUUID())=>(await db.query(
    'SELECT public.change_payment_method_v1($1,$2,$3::jsonb) AS result',[operation,kind,JSON.stringify(command)])).rows[0].result;
  const list=async()=>(await db.query('SELECT * FROM public.payment_methods WHERE owner_user_id=$1 AND is_active ORDER BY created_at,id',[owner])).rows;
  const defaults=async()=> (await list()).filter(m=>m.is_default);
  const first=randomUUID(),second=randomUUID(),third=randomUUID();
  const oldPath=owner+'/original.png',newPath=owner+'/replacement.png';
  await actor(owner);
  for(const name of [oldPath,newPath])await db.query("INSERT INTO storage.objects(bucket_id,name) VALUES ('payment-methods',$1)",[name]);
  const command={method_id:first,expected_revision:null,provider:'other',display_name:'First',account_label:'Synthetic',qr_storage_path:null,make_default:false};
  assert.equal((await change('save',command)).is_default,true);
  await change('save',{...command,method_id:second,display_name:'Second',qr_storage_path:oldPath});
  assert.equal((await defaults()).length,1); assert.equal((await defaults())[0].id,first);
  let current=await change('prefer',{method_id:second});
  assert.equal((await defaults())[0].id,second);
  const update={...command,method_id:second,display_name:'Replacement',expected_revision:current.revision,qr_storage_path:owner+'/missing.png'};
  await assert.rejects(()=>change('save',update),e=>e.code==='42501');
  assert.equal((await list()).find(m=>m.id===second).qr_storage_path,oldPath);
  const operation=randomUUID(),valid={...update,qr_storage_path:newPath};
  current=await change('save',valid,operation);
  assert.deepEqual(await change('save',valid,operation),current);
  await assert.rejects(()=>change('save',{...valid,display_name:'Conflicting'},operation),e=>e.code==='22023');
  await assert.rejects(()=>change('save',valid),e=>e.code==='40001');
  assert.equal((await defaults())[0].id,second);
  // A failure after preference/metadata writes must restore all rows.
  await db.exec('RESET ROLE');
  await db.exec("CREATE FUNCTION public.method_fault_fixture() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'fixture failure' USING ERRCODE='P9999'; END $$; CREATE TRIGGER method_fault_fixture BEFORE INSERT ON public.payment_method_operations FOR EACH ROW EXECUTE FUNCTION public.method_fault_fixture();");
  await actor(owner);
  const thirdCommand={...command,method_id:third,display_name:'Third',qr_storage_path:null,make_default:true};
  await assert.rejects(()=>change('save',thirdCommand),e=>e.code==='P9999');
  assert.equal((await list()).length,2); assert.equal((await defaults())[0].id,second);
  await db.exec('RESET ROLE'); await db.exec('DROP TRIGGER method_fault_fixture ON public.payment_method_operations; DROP FUNCTION public.method_fault_fixture()');
  await actor(owner); await change('save',thirdCommand);
  assert.equal((await defaults())[0].id,third);
  const removeOp=randomUUID();
  const removed=await change('remove',{method_id:third},removeOp);
  assert.equal(removed.is_active,false);
  assert.deepEqual(await change('remove',{method_id:third},removeOp),removed);
  assert.equal((await defaults()).length,1);
  assert.equal((await defaults())[0].id,first);
  assert.equal((await list()).some(m=>m.id===third),false);
  await assert.rejects(()=>change('save',{...command,method_id:third,expected_revision:removed.revision}),e=>e.code==='40001');
  assert.equal((await db.query('DELETE FROM storage.objects WHERE name=$1 RETURNING id',[oldPath])).rows.length,0);
  assert.equal((await db.query('UPDATE storage.objects SET name=name WHERE name=$1 RETURNING id',[newPath])).rows.length,0);
  assert((await db.query('SELECT snapshot FROM public.payment_method_revisions WHERE method_id=$1',[second])).rows.some(r=>r.snapshot.qr_storage_path===oldPath));
  assert((await db.query('SELECT snapshot FROM public.payment_method_revisions WHERE method_id=$1',[second])).rows.some(r=>r.snapshot.qr_storage_path===newPath));
  await actor(stranger);
  await assert.rejects(()=>change('prefer',{method_id:first}),e=>e.code==='42501');
  assert.equal((await db.query('SELECT * FROM public.payment_method_revisions WHERE method_id=$1',[first])).rows.length,0);
  for(const privilege of ['insert','update','delete'])assert.equal((await db.query("SELECT has_table_privilege('authenticated','public.payment_methods',$1) AS allowed",[privilege])).rows[0].allowed,false);
  await db.exec('RESET ROLE'); await db.exec('SET ROLE anon');
  await assert.rejects(()=>change('prefer',{method_id:first}),e=>e.code==='42501');
  await db.exec('RESET ROLE');
  console.log('PAYMENT_METHOD_LIFECYCLE_OK: atomic save/replace/prefer/remove, first default and successor, exact replay/conflict, stale-edit denial, failed-write rollback and immutable referenced revisions passed.');
};
